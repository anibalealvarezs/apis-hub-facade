    <p><strong>En resumen:</strong> <em>Recopilamos información personal que usted nos proporciona.</em></p>
    <p>Recopilamos la información personal que usted nos proporciona voluntariamente cuando se registra en los Servicios, expresa interés en obtener información sobre nosotros o nuestros productos y Servicios, cuando participa en actividades en los Servicios o cuando se comunica con nosotros.</p>
    <p><strong>Información Personal Proporcionada por Usted.</strong> La información personal que recopilamos depende del contexto de sus interacciones con nosotros y los Servicios, las decisiones que tome y los productos y funciones que utilice. La información personal que recopilamos puede incluir lo siguiente:</p>
