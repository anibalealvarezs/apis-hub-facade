    <h3>Portabilidad de Datos</h3>
    <p>Como usuario de APIs Hub, usted tiene el <strong>Derecho a la Portabilidad de Datos</strong>. Esto significa que puede solicitar una copia estructurada de toda la información asociada con su cuenta, incluyendo:</p>
    <ul>
        <li>Su perfil de usuario y proyectos registrados.</li>
        <li>Su configuración técnica, filtros de plataformas estandarizadas y <strong>fórmulas matemáticas personalizadas</strong>.</li>
        <li>Un volcado de sus métricas analíticas en caché más recientes y el historial de informes.</li>
    </ul>
    <p>Para solicitar una exportación de sus datos en un formato legible por máquina (JSON o CSV), póngase en contacto con nosotros en <a href="mailto:admin@apis-hub.cloud">admin@apis-hub.cloud</a>. Procesaremos su solicitud en un plazo de 30 días.</p>

