    <p><strong>En resumen:</strong> <em>Alguna información — como su dirección de Protocolo de Internet (IP) — se recopila automáticamente cuando visita nuestros Servicios.</em></p>
    <p>Recopilamos automáticamente cierta información cuando visita, usa o navega por los Servicios. Esta información no revela su identidad específica, pero puede incluir información del dispositivo y de uso, necesaria principalmente para mantener la seguridad y operación de nuestros Servicios.</p>

